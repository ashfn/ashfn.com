import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
const base = process.env.SITE_URL || 'http://localhost:4000';
const executablePath = process.env.CHROME_PATH || (existsSync('/Applications/Google Chrome.app/Contents/MacOS/Google Chrome') ? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' : undefined);
const browser = await chromium.launch({ executablePath, headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, colorScheme: 'light', reducedMotion: 'reduce', permissions: ['clipboard-read', 'clipboard-write'] });
const errors = [];
const requests = [];
const page = await context.newPage();
page.on('pageerror', e => errors.push(e.stack || e.message));
page.on('request', req => requests.push(req.url()));
await context.route('**/*', route => new URL(route.request().url()).origin === base ? route.continue() : route.fulfill({ body: '', contentType: 'text/plain' }));
await page.goto(base, { waitUntil: 'networkidle' });
assert.equal(requests.filter(url => url.endsWith('.js') && url.startsWith(base)).length, 1);
assert.ok(!requests.some(url => /snake-|tetris-/.test(url)));
assert.equal(await page.title(), 'Asher Falcon');
await page.getByRole('checkbox', { name: 'Use alternate color theme' }).click();
assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
await page.getByRole('link', { name: 'Blog', exact: true }).click();
await page.waitForURL('**/blog/');
assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
await page.getByRole('checkbox', { name: 'Use alternate color theme' }).click();
assert.equal(await page.locator('html').getAttribute('data-theme'), null);
await page.goto(base + '/blog/posts/1/');
const code = await page.locator('pre code').first().textContent();
await page.getByRole('link', { name: 'Copy code', exact: true }).first().click();
assert.equal(await page.evaluate(() => navigator.clipboard.readText()), code);
assert.equal(await page.getByRole('link', { name: 'Copied', exact: true }).count(), 1);
await page.goto(base + '/blog/posts/5/');
const firstFold = page.locator('.json-node:not([open])').first();
await firstFold.locator(':scope > summary').click();
assert.ok(await page.locator('.json-view_vscode').getByText('origin', { exact: true }).first().isVisible());
await page.locator('.json-node > summary').first().focus();
await page.keyboard.press('Enter');
assert.equal(await page.locator('.json-view_vscode').getByText('origin', { exact: true }).first().isVisible(), false);
await page.getByRole('navigation', { name: 'Table of contents' }).getByRole('link', { name: 'Lessons learned' }).click();
await page.waitForFunction(() => location.hash === '#lessons-learned' && document.querySelector('[data-toc] [aria-current]')?.textContent === 'Lessons learned');
await page.goto(base + '/blog/5/');
await page.waitForURL('**/blog/posts/5/');
await page.goto(base + '/contact/');
await page.waitForURL(base + '/');
const title = await page.title();
await page.keyboard.type('snake');
await page.waitForFunction(() => /[\u2800-\u28FF]/.test(document.title));
await page.waitForFunction(() => document.body.textContent.includes('Look at the tab!'));
await page.keyboard.press('ArrowUp');
await page.keyboard.press('Escape');
assert.equal(await page.title(), title);
await page.keyboard.type('tetris');
await page.waitForSelector('canvas');
await page.keyboard.press('Space');
await page.waitForFunction(() => /Score: [1-9]/.test(document.body.textContent));
await page.keyboard.press('Escape');
assert.equal(await page.locator('canvas').count(), 0);
await page.keyboard.type('tetris');
await page.waitForSelector('canvas');
await page.getByRole('link', { name: 'Blog', exact: true }).click();
await page.waitForURL('**/blog/');
assert.equal(await page.locator('canvas').count(), 0);
const response = await page.goto(base + '/does-not-exist/');
assert.equal(response.status(), 404);
assert.equal(await page.locator('h1').textContent(), '404');
assert.deepEqual(errors, []);
await context.close();
const nojs = await browser.newContext({ javaScriptEnabled: false });
const staticPage = await nojs.newPage();
await staticPage.goto(base + '/blog/posts/3/');
assert.ok(await staticPage.locator('h1').isVisible());
assert.ok(await staticPage.locator('pre').first().isVisible());
assert.ok(await staticPage.locator('.katex').first().isVisible());
await staticPage.goto(base + '/blog/posts/5/');
await staticPage.locator('.json-node:not([open]) > summary').first().click();
assert.ok(await staticPage.locator('.json-view_vscode').getByText('origin', { exact: true }).first().isVisible());
await nojs.close();
const blocked = await browser.newContext({ colorScheme: 'light', reducedMotion: 'reduce' });
await blocked.addInitScript(() => { Object.defineProperty(window, 'localStorage', { get() { throw new Error('Storage denied'); } }); });
const blockedPage = await blocked.newPage();
blockedPage.on('pageerror', e => errors.push(e.stack || e.message));
await blockedPage.goto(base);
await blockedPage.getByRole('checkbox', { name: 'Use alternate color theme' }).click();
assert.equal(await blockedPage.locator('html').getAttribute('data-theme'), 'dark');
await blockedPage.keyboard.type('snake');
await blockedPage.waitForFunction(() => /[\u2800-\u28FF]/.test(document.title));
await blockedPage.keyboard.press('Escape');
assert.equal(await blockedPage.title(), 'Asher Falcon');
assert.deepEqual(errors, []);
await browser.close();
console.log('Passed: lazy game loading, theme persistence, navigation, clipboard, JSON, TOC, redirects, both games, cleanup, 404, no-JS reading, blocked storage.');
